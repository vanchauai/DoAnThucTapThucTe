package com.doanthuctap.android.ui.screens

import androidx.compose.foundation.layout.*
import androidx.compose.foundation.lazy.LazyColumn
import androidx.compose.foundation.lazy.items
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Modifier
import androidx.compose.ui.unit.dp
import com.doanthuctap.android.viewmodel.MainViewModel
import com.doanthuctap.android.viewmodel.UiState

@Composable
fun ReportScreen(viewModel: MainViewModel) {
    val state by viewModel.reportHistory.collectAsState()

    LaunchedEffect(Unit) {
        viewModel.loadReportHistory()
    }

    Column(modifier = Modifier.fillMaxSize()) {
        when (val uiState = state) {
            is UiState.Loading -> {
                CircularProgressIndicator(modifier = Modifier.padding(16.dp))
            }
            is UiState.Success -> {
                Button(
                    onClick = { viewModel.generateReport(null) },
                    modifier = Modifier.padding(16.dp).fillMaxWidth()
                ) {
                    Text("Generate New Report")
                }
                LazyColumn {
                    items(uiState.data) { report ->
                        Card(modifier = Modifier.fillMaxWidth().padding(8.dp)) {
                            Column(modifier = Modifier.padding(16.dp)) {
                                Text(report.reportName, style = MaterialTheme.typography.titleMedium)
                                Text("Created At: ${report.createdAt}")
                                Text("Generated By: ${report.generatedBy ?: "System"}")
                            }
                        }
                    }
                }
            }
            is UiState.Error -> {
                Text("Error: ${uiState.message}", color = MaterialTheme.colorScheme.error, modifier = Modifier.padding(16.dp))
            }
        }
    }
}
